#!/usr/bin/env node
// Writes packages/core/src/abi.ts from the forge build artifacts in out/ (run `forge build` first).
// With --check it only compares and exits 1 if the committed file is stale (used in CI).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';

const root = fileURLToPath(new URL('..', import.meta.url));
const target = `${root}packages/core/src/abi.ts`;
const contracts = [
  ['proofOfCallAbi', 'ProofOfCall.sol', 'ProofOfCall'],
  ['aggregatorV3Abi', 'IAggregatorV3.sol', 'IAggregatorV3'],
  ['mockAggregatorV3Abi', 'MockAggregatorV3.sol', 'MockAggregatorV3'],
];

let source = '// Generated by scripts/gen-abi.mjs from the forge artifacts in out/. Do not edit by hand.\n';
for (const [name, file, contract] of contracts) {
  const artifact = JSON.parse(readFileSync(`${root}out/${file}/${contract}.json`, 'utf8'));
  source += `\nexport const ${name} = ${JSON.stringify(artifact.abi)} as const;\n`;
}
const options = (await prettier.resolveConfig(target)) ?? {};
const formatted = await prettier.format(source, { ...options, filepath: target });

if (process.argv.includes('--check')) {
  const current = readFileSync(target, 'utf8');
  if (current !== formatted) {
    console.error('packages/core/src/abi.ts is stale: run `forge build && npm run abi` and commit the result.');
    process.exit(1);
  }
  console.log('abi.ts matches the forge artifacts');
} else {
  writeFileSync(target, formatted);
  console.log(`wrote ${target}`);
}
